'use strict';
const assert=require('node:assert/strict');
const {controller,STATES}=require('../pairing-gate.js');
function newGate(){return controller()}
const empty=newGate();
assert.equal(empty.allowLessonData(),false,'new connection denied');
assert.equal(empty.isAuthenticated(),false,'new connection unauthenticated');
const verifiedOnly=newGate();
assert.equal(verifiedOnly.markVerified(true),true);
assert.equal(verifiedOnly.allowLessonData(),false,'crypto verification alone cannot approve');
const approvedOnly=newGate();
assert.equal(approvedOnly.teacherDecision(true),true);
assert.equal(approvedOnly.allowLessonData(),false,'teacher approval alone cannot authenticate');
assert.equal(approvedOnly.markVerified(true),true);
assert.equal(approvedOnly.allowLessonData(),true,'both gates required');
assert.equal(approvedOnly.status(),STATES.ACTIVE);
assert.throws(()=>approvedOnly.teacherDecision(true),/Already active/,'cannot repeat approval');
approvedOnly.close();
assert.equal(approvedOnly.allowLessonData(),false,'disconnect revokes authorization');
assert.throws(()=>approvedOnly.markVerified(true),/Pairing closed/,'closed session cannot reopen');
const rejected=newGate();
assert.equal(rejected.teacherDecision(false),false);
assert.equal(rejected.allowLessonData(),false);
assert.throws(()=>rejected.markVerified(true),/Pairing closed/);
const forged=newGate();
assert.equal(forged.markVerified('true'),false,'non-boolean proof rejected');
assert.equal(forged.allowLessonData(),false);
const fresh=newGate();
assert.equal(fresh.allowLessonData(),false,'new connection cannot inherit approval');
console.log('PASS: isolated pairing authorization gate (NOT wired into Teacher/Board)');
